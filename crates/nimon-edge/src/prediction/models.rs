//! Prediction models for device failure prediction
//!
//! This module provides three prediction model implementations:
//! - [`EwmaAnomalyDetector`]: EWMA-based anomaly detection using z-scores
//! - [`TrendPredictor`]: Linear regression trend detection
//! - [`ThresholdPredictor`]: Simple threshold-based prediction

use chrono::{DateTime, Utc};
use std::collections::VecDeque;

use nimon_core::actor::messages::PredictionType;

/// Prediction model trait
///
/// Implementations analyze metric values over time and generate
/// predictions about potential device failures.
pub trait PredictionModel: Send + Sync {
    /// Feed a new metric value to the model.
    ///
    /// Returns a [`ModelUpdate`] indicating whether a new or updated
    /// prediction was generated, or nothing changed.
    fn update(&mut self, metric_name: &str, value: f64, timestamp: DateTime<Utc>) -> ModelUpdate;

    /// Get the current prediction for a metric, if any.
    ///
    /// Some models generate predictions eagerly in `update()`, so this
    /// may return `None` even after an update.
    fn predict(&self, metric_name: &str) -> Option<Prediction>;
}

/// Result of a model update
#[derive(Debug, Clone)]
pub enum ModelUpdate {
    /// No prediction change
    NoPrediction,
    /// A new prediction was generated
    NewPrediction(Prediction),
    /// An existing prediction was updated
    UpdatedPrediction(Prediction),
}

/// A prediction generated by a model
#[derive(Debug, Clone)]
pub struct Prediction {
    /// Type of predicted failure
    pub prediction_type: PredictionType,
    /// Probability of failure (0.0 to 1.0)
    pub probability: f64,
    /// Confidence in this prediction (0.0 to 1.0)
    pub confidence: f64,
    /// Estimated time to failure in minutes
    pub eta_minutes: Option<i32>,
    /// Human-readable reason for this prediction
    pub reason: String,
    /// Model version identifier
    pub model_version: String,
}

