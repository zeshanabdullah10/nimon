    // -- Integration Tests --

    #[test]
    fn test_multiple_models_on_same_data() {
        let mut ewma = EwmaAnomalyDetector::default_params();
        let mut trend = TrendPredictor::new(10, 2.0, PredictionType::Overheating);
        let mut threshold = ThresholdPredictor::new(75.0, 65.0, PredictionType::Overheating);
        let now = Utc::now();

        // Normal values
        for val in [30.0, 31.0, 30.5, 31.0, 30.0] {
            ewma.update("temperature", val, now);
            trend.update("temperature", val, now);
            threshold.update("temperature", val, now);
        }

        // Anomalous spike
        let _ewma_result = ewma.update("temperature", 90.0, now);
        let _trend_result = trend.update("temperature", 90.0, now);
        let threshold_result = threshold.update("temperature", 90.0, now);

        // At least threshold should fire for a value of 90
        assert!(matches!(threshold_result, ModelUpdate::NewPrediction(_)));
    }
