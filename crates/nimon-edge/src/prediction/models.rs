/// Linear regression trend detection model.
///
/// Tracks recent values and computes the slope (rate of change).
/// Flags predictions when the trend exceeds a threshold rate.
pub struct TrendPredictor {
    /// Number of recent values to consider for trend calculation
    pub window_size: usize,
    /// Rate-of-change threshold that triggers a prediction
    pub threshold_rate: f64,
    /// Recent values (time-ordered)
    pub values: VecDeque<f64>,
    /// Type of prediction to generate
    prediction_type: PredictionType,
}

impl TrendPredictor {
    /// Create a new trend predictor.
    ///
    /// # Arguments
    /// * `window_size` - Number of values in the sliding window
    /// * `threshold_rate` - Minimum slope to trigger a prediction
    /// * `prediction_type` - Type of prediction to emit
    pub fn new(
        window_size: usize,
        threshold_rate: f64,
        prediction_type: PredictionType,
    ) -> Self {
        Self {
            window_size,
            threshold_rate,
            values: VecDeque::new(),
            prediction_type,
        }
    }

    /// Calculate the linear regression slope of recent values.
    ///
    /// Returns the slope (rate of change per sample).
    pub fn calculate_trend(&self) -> Option<f64> {
        let n = self.values.len();
        if n < 3 {
            return None;
        }

        // Linear regression: y = mx + b
        // m = (n * sum(xy) - sum(x) * sum(y)) / (n * sum(x^2) - sum(x)^2)
        let values: Vec<f64> = self.values.iter().copied().collect();
        let n_f = n as f64;

        let sum_x: f64 = (0..n).map(|i| i as f64).sum();
        let sum_y: f64 = values.iter().sum();
        let sum_xy: f64 = values.iter().enumerate().map(|(i, v)| i as f64 * v).sum();
        let sum_x2: f64 = (0..n).map(|i| (i as f64).powi(2)).sum();

        let denominator = n_f * sum_x2 - sum_x * sum_x;
        if denominator.abs() < 1e-10 {
            return Some(0.0);
        }

        Some((n_f * sum_xy - sum_x * sum_y) / denominator)
    }
}

impl PredictionModel for TrendPredictor {
    fn update(&mut self, _metric_name: &str, value: f64, _timestamp: DateTime<Utc>) -> ModelUpdate {
        self.values.push_back(value);

        if self.values.len() > self.window_size {
            self.values.pop_front();
        }

        // Need at least 3 samples for trend analysis
        if self.values.len() < 3 {
            return ModelUpdate::NoPrediction;
        }

        let slope = match self.calculate_trend() {
            Some(s) => s,
            None => return ModelUpdate::NoPrediction,
        };

        // Only trigger on upward trends exceeding threshold
        if slope > self.threshold_rate {
            let latest = *self.values.back().unwrap_or(&0.0);
            let probability = (slope / self.threshold_rate).min(1.0);
            let confidence = 0.6 + 0.2 * ((self.values.len() as f64 / self.window_size as f64).min(1.0));

            // Estimate time to critical threshold based on current slope
            let eta_minutes = if slope > 0.0 {
                // Assume a critical value is 2x the latest value
                let critical_value = latest * 2.0;
                let samples_to_critical = (critical_value - latest) / slope;
                Some((samples_to_critical * 60.0) as i32) // Assume 1 sample = 1 minute
            } else {
                None
            };

            return ModelUpdate::NewPrediction(Prediction {
                prediction_type: self.prediction_type.clone(),
                probability,
                confidence: confidence.min(1.0),
                eta_minutes,
                reason: format!(
                    "Upward trend detected: slope={:.3}/sample (threshold={:.3}), current={:.2}",
                    slope, self.threshold_rate, latest
                ),
                model_version: "trend-v1".to_string(),
            });
        }

        ModelUpdate::NoPrediction
    }

    fn predict(&self, _metric_name: &str) -> Option<Prediction> {
        // Trend predictor generates predictions eagerly in update()
        None
    }
}

