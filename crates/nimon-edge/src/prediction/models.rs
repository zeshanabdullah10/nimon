/// Simple threshold-based prediction model.
///
/// Compares metric values against configured warning and critical thresholds.
/// Immediately flags when a value exceeds the critical threshold.
pub struct ThresholdPredictor {
    /// Critical threshold - values at or above this trigger a prediction
    pub critical_threshold: f64,
    /// Warning threshold - values above this increase prediction probability
    pub warning_threshold: f64,
    /// Type of prediction to generate
    prediction_type: PredictionType,
}

impl ThresholdPredictor {
    /// Create a new threshold predictor.
    ///
    /// # Arguments
    /// * `critical_threshold` - Critical threshold value
    /// * `warning_threshold` - Warning threshold value
    /// * `prediction_type` - Type of prediction to emit
    pub fn new(
        critical_threshold: f64,
        warning_threshold: f64,
        prediction_type: PredictionType,
    ) -> Self {
        Self {
            critical_threshold,
            warning_threshold,
            prediction_type,
        }
    }
}

impl PredictionModel for ThresholdPredictor {
    fn update(&mut self, _metric_name: &str, value: f64, _timestamp: DateTime<Utc>) -> ModelUpdate {
        if value >= self.critical_threshold {
            return ModelUpdate::NewPrediction(Prediction {
                prediction_type: self.prediction_type.clone(),
                probability: 0.9,
                confidence: 0.95,
                eta_minutes: Some(0),
                reason: format!(
                    "Value {:.2} exceeds critical threshold {:.2}",
                    value, self.critical_threshold
                ),
                model_version: "threshold-v1".to_string(),
            });
        } else if value >= self.warning_threshold {
            // Value in warning range - generate a lower-confidence prediction
            let ratio = (value - self.warning_threshold)
                / (self.critical_threshold - self.warning_threshold);
            return ModelUpdate::NewPrediction(Prediction {
                prediction_type: self.prediction_type.clone(),
                probability: 0.5 + 0.3 * ratio,
                confidence: 0.6,
                eta_minutes: None,
                reason: format!(
                    "Value {:.2} is in warning range ({:.2} - {:.2})",
                    value, self.warning_threshold, self.critical_threshold
                ),
                model_version: "threshold-v1".to_string(),
            });
        }

        ModelUpdate::NoPrediction
    }

    fn predict(&self, _metric_name: &str) -> Option<Prediction> {
        // Threshold predictor generates predictions eagerly in update()
        None
    }
}

